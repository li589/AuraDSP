/*
 * rbj_biquad_generator.dart — RBJ 双二阶滤波器 EEL2 脚本生成引擎
 *
 * 遵循 Clean-Room 原则自研实现：
 * 基于 Robert Bristow-Johnson Audio EQ Cookbook 算法模型，
 * 将 ApoConfiguration 解析结果转化为高效、自适应采样率、面向对象封装的 EEL2 脚本。
 */

import 'equalizer_apo_parser.dart';

/// EEL2 脚本生成器
class RbjBiquadGenerator {
  /// 生成完整的 EEL2 源代码
  static String generate({
    required ApoConfiguration config,
    String presetName = 'EqualizerAPO Preset',
    bool channelSwap = false,
    bool invertPolarity = false,
  }) {
    final sb = StringBuffer();

    // 1. 文件头与元数据说明
    sb.writeln('/*');
    sb.writeln(' * Generated by AuraDSP EqualizerAPO Converter');
    sb.writeln(' * Preset: $presetName');
    sb.writeln(' * Total Active Filters: ${config.activeFilters.length}');
    sb.writeln(' * Global Preamp: ${config.globalPreamp.toStringAsFixed(2)} dB');
    if (config.hasStereoDifference) {
      sb.writeln(' * Left Preamp: ${config.leftPreamp.toStringAsFixed(2)} dB');
      sb.writeln(' * Right Preamp: ${config.rightPreamp.toStringAsFixed(2)} dB');
    }
    if (channelSwap) sb.writeln(' * Channel Swap: Enabled (L <-> R)');
    if (invertPolarity) sb.writeln(' * Polarity Inversion: Enabled (180 deg)');
    sb.writeln(' */');
    sb.writeln();

    sb.writeln('desc: $presetName');
    sb.writeln();

    // 2. 检查是否有有效滤波器：无滤波器时输出极简轻量纯前级增益脚本
    final activeFilters = config.activeFilters;
    final gPreamp = config.globalPreamp;
    final lPreamp = config.leftPreamp;
    final rPreamp = config.rightPreamp;

    if (activeFilters.isEmpty) {
      sb.writeln('@init');
      sb.writeln('// --- Preamp Linear Gains (Preamp Only Mode) ---');
      sb.writeln('g_preamp_db = ${_formatNum(gPreamp)};');
      sb.writeln('l_preamp_db = ${_formatNum(lPreamp)};');
      sb.writeln('r_preamp_db = ${_formatNum(rPreamp)};');
      sb.writeln('gain_l = 10 ^ ((g_preamp_db + l_preamp_db) / 20);');
      sb.writeln('gain_r = 10 ^ ((g_preamp_db + r_preamp_db) / 20);');
      sb.writeln();

      sb.writeln('@sample');
      if (channelSwap) {
        sb.writeln('// Step 1: Channel Swap');
        sb.writeln('tmp_spl = spl0; spl0 = spl1; spl1 = tmp_spl;');
        sb.writeln();
      }
      sb.writeln('// Step 2: Apply Preamp Gains');
      sb.writeln('spl0 *= gain_l;');
      sb.writeln('spl1 *= gain_r;');
      if (invertPolarity) {
        sb.writeln();
        sb.writeln('// Step 3: Polarity Inversion (180 deg)');
        sb.writeln('spl0 = -spl0;');
        sb.writeln('spl1 = -spl1;');
      }
      return sb.toString();
    }

    // 2. @init 段：定义常量、RBJ 函数和初始化滤波器系数
    sb.writeln('@init');
    sb.writeln('PI = 3.141592653589793;');
    sb.writeln('srate = (srate > 0) ? srate : 48000; // Sample rate fallback guard');
    sb.writeln();

    // 2.1 增益计算
    sb.writeln('// --- Preamp Linear Gains ---');
    sb.writeln('g_preamp_db = ${_formatNum(gPreamp)};');
    sb.writeln('l_preamp_db = ${_formatNum(lPreamp)};');
    sb.writeln('r_preamp_db = ${_formatNum(rPreamp)};');
    sb.writeln('gain_l = 10 ^ ((g_preamp_db + l_preamp_db) / 20);');
    sb.writeln('gain_r = 10 ^ ((g_preamp_db + r_preamp_db) / 20);');
    sb.writeln();

    // 2.2 核心 RBJ 滤波器计算与处理函数
    _writeRbjFunctions(sb);

    // 2.3 实例化并计算滤波器系数
    sb.writeln('// --- Initialize Filter Instances ---');
    final globalFilters = config.globalFilters;
    final leftFilters = config.leftFilters;
    final rightFilters = config.rightFilters;

    if (globalFilters.isEmpty && leftFilters.isEmpty && rightFilters.isEmpty) {
      sb.writeln('// (No active filters configured)');
    }

    if (globalFilters.isNotEmpty) {
      sb.writeln('// Global Filters (Both Channels)');
      for (var i = 0; i < globalFilters.length; i++) {
        final f = globalFilters[i];
        final id = i + 1;
        final fn = _calcFuncName(f.type);
        final args = _calcFuncArgs(f);
        sb.writeln('// Filter $id: ${f.type.code} ${f.freq}Hz ${f.gainDb}dB Q=${f.q}');
        sb.writeln('g_f${id}_L.$fn($args);');
        sb.writeln('g_f${id}_R.$fn($args);');
      }
      sb.writeln();
    }

    if (leftFilters.isNotEmpty) {
      sb.writeln('// Channel L Specific Filters');
      for (var i = 0; i < leftFilters.length; i++) {
        final f = leftFilters[i];
        final id = i + 1;
        final fn = _calcFuncName(f.type);
        final args = _calcFuncArgs(f);
        sb.writeln('// Left Filter $id: ${f.type.code} ${f.freq}Hz ${f.gainDb}dB Q=${f.q}');
        sb.writeln('l_f$id.$fn($args);');
      }
      sb.writeln();
    }

    if (rightFilters.isNotEmpty) {
      sb.writeln('// Channel R Specific Filters');
      for (var i = 0; i < rightFilters.length; i++) {
        final f = rightFilters[i];
        final id = i + 1;
        final fn = _calcFuncName(f.type);
        final args = _calcFuncArgs(f);
        sb.writeln('// Right Filter $id: ${f.type.code} ${f.freq}Hz ${f.gainDb}dB Q=${f.q}');
        sb.writeln('r_f$id.$fn($args);');
      }
      sb.writeln();
    }

    // 3. @sample 段：每个音频采样点执行
    sb.writeln('@sample');
    if (channelSwap) {
      sb.writeln('// Step 1: Channel Swap');
      sb.writeln('tmp_swap = spl0;');
      sb.writeln('spl0 = spl1;');
      sb.writeln('spl1 = tmp_swap;');
      sb.writeln();
    }

    sb.writeln('// Step 2: Apply Preamp Gains');
    sb.writeln('spl0 *= gain_l;');
    sb.writeln('spl1 *= gain_r;');
    sb.writeln();

    if (globalFilters.isNotEmpty) {
      sb.writeln('// Step 3: Global Cascade Filters');
      for (var i = 0; i < globalFilters.length; i++) {
        final id = i + 1;
        sb.writeln('spl0 = g_f${id}_L.process_biquad(spl0);');
        sb.writeln('spl1 = g_f${id}_R.process_biquad(spl1);');
      }
      sb.writeln();
    }

    if (leftFilters.isNotEmpty) {
      sb.writeln('// Step 4: Left Channel Specific Filters');
      for (var i = 0; i < leftFilters.length; i++) {
        final id = i + 1;
        sb.writeln('spl0 = l_f$id.process_biquad(spl0);');
      }
      sb.writeln();
    }

    if (rightFilters.isNotEmpty) {
      sb.writeln('// Step 5: Right Channel Specific Filters');
      for (var i = 0; i < rightFilters.length; i++) {
        final id = i + 1;
        sb.writeln('spl1 = r_f$id.process_biquad(spl1);');
      }
      sb.writeln();
    }

    if (invertPolarity) {
      sb.writeln('// Step 6: Polarity Inversion (180 deg)');
      sb.writeln('spl0 = -spl0;');
      sb.writeln('spl1 = -spl1;');
      sb.writeln();
    }

    return sb.toString();
  }

  static String _formatNum(double val) {
    if (val == val.roundToDouble()) {
      return val.toStringAsFixed(1);
    }
    return val.toString();
  }

  static String _calcFuncName(ApoFilterType type) {
    return switch (type) {
      ApoFilterType.peaking => 'calc_peak',
      ApoFilterType.lowShelf => 'calc_lowshelf',
      ApoFilterType.highShelf => 'calc_highshelf',
      ApoFilterType.lowPass => 'calc_lowpass',
      ApoFilterType.highPass => 'calc_highpass',
      ApoFilterType.bandPass => 'calc_bandpass',
      ApoFilterType.notch => 'calc_notch',
    };
  }

  static String _calcFuncArgs(ApoFilter f) {
    final freq = _formatNum(f.freq);
    final q = _formatNum(f.q);
    final gain = _formatNum(f.gainDb);

    if (f.type == ApoFilterType.lowPass ||
        f.type == ApoFilterType.highPass ||
        f.type == ApoFilterType.bandPass ||
        f.type == ApoFilterType.notch) {
      return '$freq, $q';
    }
    return '$freq, $q, $gain';
  }

  static void _writeRbjFunctions(StringBuffer sb) {
    sb.writeln('// --- RBJ Biquad Filter Calculation Model ---');
    sb.writeln('''function calc_peak(freq, q, gain_db) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);
  A = 10 ^ (gain_db / 40);

  b0 = 1 + alpha * A;
  b1 = -2 * cos(w0);
  b2 = 1 - alpha * A;
  a0 = 1 + alpha / A;
  a1 = -2 * cos(w0);
  a2 = 1 - alpha / A;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function calc_lowshelf(freq, q, gain_db) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);
  A = 10 ^ (gain_db / 40);
  cos_w0 = cos(w0);
  sqrt_A2_alpha = 2 * sqrt(A) * alpha;

  b0 = A * ((A + 1) - (A - 1) * cos_w0 + sqrt_A2_alpha);
  b1 = 2 * A * ((A - 1) - (A + 1) * cos_w0);
  b2 = A * ((A + 1) - (A - 1) * cos_w0 - sqrt_A2_alpha);
  a0 = (A + 1) + (A - 1) * cos_w0 + sqrt_A2_alpha;
  a1 = -2 * ((A - 1) + (A + 1) * cos_w0);
  a2 = (A + 1) + (A - 1) * cos_w0 - sqrt_A2_alpha;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function calc_highshelf(freq, q, gain_db) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);
  A = 10 ^ (gain_db / 40);
  cos_w0 = cos(w0);
  sqrt_A2_alpha = 2 * sqrt(A) * alpha;

  b0 = A * ((A + 1) + (A - 1) * cos_w0 + sqrt_A2_alpha);
  b1 = -2 * A * ((A - 1) + (A + 1) * cos_w0);
  b2 = A * ((A + 1) + (A - 1) * cos_w0 - sqrt_A2_alpha);
  a0 = (A + 1) - (A - 1) * cos_w0 + sqrt_A2_alpha;
  a1 = 2 * ((A - 1) - (A + 1) * cos_w0);
  a2 = (A + 1) - (A - 1) * cos_w0 - sqrt_A2_alpha;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function calc_lowpass(freq, q) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);
  cos_w0 = cos(w0);

  b1 = 1 - cos_w0;
  b0 = b1 * 0.5;
  b2 = b0;
  a0 = 1 + alpha;
  a1 = -2 * cos_w0;
  a2 = 1 - alpha;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function calc_highpass(freq, q) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);
  cos_w0 = cos(w0);

  b1 = -(1 + cos_w0);
  b0 = -b1 * 0.5;
  b2 = b0;
  a0 = 1 + alpha;
  a1 = -2 * cos_w0;
  a2 = 1 - alpha;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function calc_bandpass(freq, q) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);

  b0 = alpha;
  b1 = 0;
  b2 = -alpha;
  a0 = 1 + alpha;
  a1 = -2 * cos(w0);
  a2 = 1 - alpha;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function calc_notch(freq, q) instance(b0, b1, b2, a1, a2) (
  w0 = 2 * PI * freq / srate;
  alpha = sin(w0) / (2 * q);
  cos_w0 = cos(w0);

  b0 = 1;
  b1 = -2 * cos_w0;
  b2 = 1;
  a0 = 1 + alpha;
  a1 = -2 * cos_w0;
  a2 = 1 - alpha;

  inv_a0 = 1 / a0;
  this.b0 = b0 * inv_a0;
  this.b1 = b1 * inv_a0;
  this.b2 = b2 * inv_a0;
  this.a1 = a1 * inv_a0;
  this.a2 = a2 * inv_a0;
);

function process_biquad(xn) instance(b0, b1, b2, a1, a2, x1, x2, y1, y2) (
  yn = this.b0 * xn + this.b1 * this.x1 + this.b2 * this.x2 - this.a1 * this.y1 - this.a2 * this.y2;
  this.x2 = this.x1;
  this.x1 = xn;
  this.y2 = this.y1;
  this.y1 = yn;
  yn;
);''');
    sb.writeln();
  }
}
