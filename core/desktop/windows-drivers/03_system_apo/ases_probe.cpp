// ases_probe.cpp — 遍历 AudioSes DllGetClassObject 支持的 CLSID + QI IAudioSessionControl。
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <audiosessiontypes.h>
#include <audioclient.h>
#include <cstdio>

int main() {
    HMODULE h = LoadLibraryW(L"C:\\Windows\\System32\\AudioSes.dll");
    if (!h) { printf("load fail %lu\n", GetLastError()); return 1; }
    auto getClass = (HRESULT(__stdcall*)(REFCLSID, REFIID, void**))GetProcAddress(h, "DllGetClassObject");
    if (!getClass) { printf("no DllGetClassObject\n"); return 1; }
    IID iidFactory = {0x00000001, 0x0000, 0x0000, {0xc0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x46}};
    // AudioSes 14 个类 + 音频会话关键类 {4e5aa6d0-ec2e-45f4-8f80-c5...}
    const GUID cands[] = {
        {0x1d7ad053, 0xd487, 0x484a, {0x82, 0x5b, 0xc3, 0x8b, 0x53, 0x77, 0x1e, 0xec}},
        {0x294935ce, 0xf637, 0x4e7c, {0xa4, 0x1b, 0xab, 0x25, 0x54, 0x60, 0xb8, 0x62}},
        {0x41fccc3a, 0x1fa1, 0x4949, {0x95, 0x3a, 0x6e, 0xe6, 0x1c, 0x46, 0xa4, 0xd1}},
        {0x444f7305, 0x1d7d, 0x4be9, {0x8c, 0x29, 0xcc, 0x3f, 0x1d, 0x22, 0x0c, 0x40}},
        {0x562462dd, 0x4f9a, 0x4110, {0x9d, 0x6a, 0xc3, 0xca, 0x04, 0x07, 0xff, 0x76}},
        {0x870af99c, 0x171d, 0x4f9e, {0xaf, 0x0d, 0xe6, 0x3d, 0xf4, 0x0c, 0x2b, 0xc9}},
        {0x8a561b8f, 0x0f41, 0x4f55, {0x8f, 0x52, 0x47, 0x0e, 0xe7, 0xc7, 0xb5, 0x28}},
        {0x8d9945c3, 0xa621, 0x4f52, {0x86, 0x41, 0x6d, 0x8b, 0x75, 0x5f, 0x42, 0xe2}},
        {0xf4ece1db, 0xc480, 0x458f, {0x84, 0x54, 0x70, 0xc5, 0x5f, 0xec, 0xa4, 0xa4}},
        {0xede7f087, 0x890f, 0x491c, {0xb9, 0x06, 0x9a, 0xbb, 0x31, 0x89, 0x69, 0x60}},
        {0x6ec153c1, 0x371e, 0x47e1, {0xa8, 0x96, 0x2f, 0x7f, 0x80, 0xeb, 0x78, 0x42}},
    };
    for (const auto& c : cands) {
        void* f = nullptr;
        HRESULT hr = getClass(c, iidFactory, &f);
        if (SUCCEEDED(hr) && f) { ((IUnknown*)f)->Release(); printf("class ok\n"); }
        else printf("class hr=0x%08lX\n", (unsigned long)hr);
    }
    FreeLibrary(h);
    return 0;
}
